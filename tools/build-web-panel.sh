#!/bin/sh
# The device's web panel is the PC App's page: TinytoshPC/src, which runs in both places.
# This packs that page into one gzipped file and writes it as TinytoshESP32/WebPanel.h, which
# the firmware serves as is. Run it after changing anything in TinytoshPC/src.
# With --check it writes nothing and fails if WebPanel.h is out of date.
set -e
cd "$(dirname "$0")/.."

exec python3 - "$1" <<'PY'
import gzip, pathlib, sys

source = pathlib.Path("TinytoshPC/src")
header = pathlib.Path("TinytoshESP32/WebPanel.h")

page = (source / "index.html").read_text()
style_tag = '<link rel="stylesheet" href="styles.css" />'
script_tag = '<script type="module" src="/main.js" defer></script>'
assert page.count(style_tag) == 1 and page.count(script_tag) == 1, "index.html no longer has the tags this script replaces"
script = (source / "main.js").read_text()
assert "</script" not in script, "main.js contains </script, which would end the inlined script early"
page = page.replace(style_tag, "<style>" + (source / "styles.css").read_text() + "</style>")
page = page.replace(script_tag, '<script type="module">' + script + "</script>")

packed = gzip.compress(page.encode(), compresslevel=9, mtime=0)
rows = [", ".join(f"0x{byte:02x}" for byte in packed[i:i + 16]) for i in range(0, len(packed), 16)]
text = (
    "// Generated by tools/build-web-panel.sh from TinytoshPC/src. Do not edit.\n"
    "#ifndef WEB_PANEL_H\n#define WEB_PANEL_H\n\n#include <Arduino.h>\n\n"
    f"// The web panel: one HTML page, gzipped. {len(page.encode())} bytes before packing.\n"
    f"const size_t WEB_PANEL_GZ_LEN = {len(packed)};\n"
    "const uint8_t WEB_PANEL_GZ[] PROGMEM = {\n  " + ",\n  ".join(rows) + "\n};\n\n#endif\n"
)

if sys.argv[1] == "--check":
    if not header.exists() or header.read_text() != text:
        sys.exit("TinytoshESP32/WebPanel.h is out of date. Run tools/build-web-panel.sh.")
    print("WebPanel.h matches TinytoshPC/src.")
else:
    header.write_text(text)
    print(f"WebPanel.h written: {len(packed)} bytes packed from {len(page.encode())}.")
PY
